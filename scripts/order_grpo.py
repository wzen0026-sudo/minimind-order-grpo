"""Run MiniMind's order GRPO comparison from the repository's scripts directory."""

import argparse
import ast
from decimal import Decimal
import json
from pathlib import Path
import random
import re
import subprocess
import sys
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parent))
import order_eval


MAX_TURNS = order_eval.MAX_TURNS
MODES = ("final", "process")
GENERATED_HEADER = "# Generated by scripts/order_grpo.py.\n"
SUFFIX = ' 请使用工具核实数据。最终只输出 JSON，例如 {"total":"0.00"}，单位为元。'


def prepare_data(root):
    dataset = root / "dataset"
    sft_file = dataset / "order_sft_train.jsonl"
    if not sft_file.is_file():
        raise FileNotFoundError(f"Missing SFT training data: {sft_file}")
    used_orders = {case[0] for case in order_eval.CASES}
    used_products = {case[1] for case in order_eval.CASES}
    with sft_file.open(encoding="utf-8") as handle:
        for line in handle:
            for message in json.loads(line)["conversations"]:
                for call in json.loads(message.get("tool_calls") or "[]"):
                    if call["name"] == "lookup_order":
                        used_orders.add(call["arguments"]["order_id"])
                    elif call["name"] == "lookup_price":
                        used_products.add(call["arguments"]["product_id"])

    rng = random.Random(5048)
    orders = rng.sample([
        f"{prefix}{number}" for prefix in "ABCD" for number in range(100, 1000)
        if f"{prefix}{number}" not in used_orders
    ], 72)
    products = rng.sample([
        f"P{number}" for number in range(100, 1000) if f"P{number}" not in used_products
    ], 72)
    templates = [case[4].replace(case[0], "{id}") for case in order_eval.CASES]
    cases = [
        (oid, pid, rng.randint(1, 9), f"{Decimal(rng.randint(200, 9999)) / 100:.2f}",
         templates[index % len(templates)].format(id=oid))
        for index, (oid, pid) in enumerate(zip(orders, products))
    ]
    train, holdout = cases[:48], cases[48:]
    with (dataset / "order_grpo_train.jsonl").open("w", encoding="utf-8") as handle:
        for case in train:
            _, _, quantity, price, question = case
            conversations = [
                {"role": "system", "content": "", "tools": json.dumps(order_eval.TOOLS, ensure_ascii=False)},
                {"role": "user", "content": question + SUFFIX},
                {"role": "assistant", "content": json.dumps({"total": f"{quantity * Decimal(price):.2f}"})},
            ]
            handle.write(json.dumps({"conversations": conversations, "gt": case}, ensure_ascii=False) + "\n")
    with (dataset / "order_grpo_holdout.jsonl").open("w", encoding="utf-8") as handle:
        for case in holdout:
            handle.write(json.dumps(case, ensure_ascii=False) + "\n")
    return train, holdout


def configure_tools(cases):
    order_eval.ORDERS = {
        oid: {"product_id": pid, "quantity": qty} for oid, pid, qty, _, _ in cases
    }
    order_eval.PRICES = {pid: price for _, pid, _, price, _ in cases}


def configure_training_tools(data_path):
    with Path(data_path).open(encoding="utf-8") as handle:
        configure_tools([json.loads(line)["gt"] for line in handle])


def score(case, turn_outputs, parse_calls, mode, unfinished):
    order_id, product_id, quantity, unit_price, _ = case
    expected_total = quantity * Decimal(unit_price)
    final = None
    if turn_outputs and not unfinished:
        try:
            final = json.loads(turn_outputs[-1].rsplit("</think>", 1)[-1].strip())
        except json.JSONDecodeError:
            pass
    final_reward = float(isinstance(final, dict) and order_eval.money(final.get("total")) == expected_total)
    if mode == "final":
        return final_reward

    calls_by_turn = [parse_calls(output) for output in turn_outputs]
    expected = [
        ("lookup_order", {"order_id": order_id}),
        ("lookup_price", {"product_id": product_id}),
        ("calculate_total", {"quantity": quantity, "unit_price": Decimal(unit_price)}),
    ]
    correct_steps = 0
    for (name, expected_arguments), calls in zip(expected, calls_by_turn):
        if len(calls) != 1 or calls[0].get("name") != name:
            break
        arguments = calls[0].get("arguments")
        if not isinstance(arguments, dict):
            break
        if name == "calculate_total":
            if type(arguments.get("quantity")) is not int:
                break
            arguments = {**arguments, "unit_price": order_eval.money(arguments.get("unit_price"))}
        if any(arguments.get(key) != value for key, value in expected_arguments.items()):
            break
        correct_steps += 1
    attempted_calls = sum(
        max(len(calls), output.count("<tool_call>"))
        for calls, output in zip(calls_by_turn, turn_outputs)
    )
    return final_reward + 0.25 * correct_steps - 0.25 * (attempted_calls - correct_steps)


def adapt_trainer(source):
    def replace_once(old, new):
        nonlocal source
        if source.count(old) != 1:
            raise ValueError(f"Trainer source differs at: {old.splitlines()[0]}")
        source = source.replace(old, new, 1)

    replacements = {
        "execute_tool": """def execute_tool(name, args):
    return order_experiment.order_eval.execute_tool(name, args)
""",
        "calculate_rewards": """def calculate_rewards(prompts, completions, gt_batch, tools_batch, num_gen, reward_model=None, device="cuda", turn_outputs_batch=None, unfinished_batch=None):
    scores = [
        order_experiment.score(gt_batch[index // num_gen], outputs, parse_tool_calls,
                               args.order_reward, unfinished_batch[index])
        for index, outputs in enumerate(turn_outputs_batch)
    ]
    return torch.tensor(scores, device=device, dtype=torch.float32)
""",
    }
    functions = {
        node.name: node for node in ast.parse(source).body if isinstance(node, ast.FunctionDef)
    }
    lines = source.splitlines(keepends=True)
    for name in sorted(replacements, key=lambda name: functions[name].lineno, reverse=True):
        node = functions[name]
        lines[node.lineno - 1:node.end_lineno] = [replacements[name]]
    source = "".join(lines)

    replace_once(
        "import datasets  # noqa: F401  # Windows pyarrow/torch DLL conflict workaround (issue #771)",
        "from scripts import order_grpo as order_experiment\n\n"
        "import datasets  # noqa: F401  # Windows pyarrow/torch DLL conflict workaround (issue #771)",
    )
    replace_once("args.num_generations, max_turns=3",
                 "args.num_generations, max_turns=order_experiment.MAX_TURNS")
    replace_once("response_mask.extend([int(t != tokenizer.eos_token_id) for t in new_ids])",
                 "response_mask.extend([1] * len(new_ids))")
    # Each assistant turn has its own EOS; tool observations already have mask zero.
    start = source.index("        is_eos = ")
    end = source.index("        token_counts = ", start)
    source = source[:start] + source[end:]
    replace_once(
        "    args = parser.parse_args()",
        "    parser.add_argument('--order_reward', choices=('final', 'process'), required=True)\n"
        "    args = parser.parse_args()\n"
        "    order_experiment.configure_training_tools(args.data_path)",
    )
    start = source.index("    reward_model = ")
    end = source.index("    # Rollout", start)
    source = source[:start] + "    reward_model = None\n" + source[end:]
    compile(source, "train_order_agent.py", "exec")
    return GENERATED_HEADER + source


def train(root, trainer, mode):
    weight = f"order_grpo_{mode}"
    print(f"\n[Training] {weight} from order_sft", flush=True)
    subprocess.run([
        sys.executable, str(trainer), "--data_path", "../dataset/order_grpo_train.jsonl",
        "--from_weight", "order_sft", "--save_weight", weight,
        "--order_reward", mode, "--loss_type", "grpo", "--thinking_ratio", "0",
        "--epochs", "1", "--batch_size", "1", "--num_generations", "4",
        "--num_workers", "0", "--max_gen_len", "96", "--max_total_len", "1280",
        "--learning_rate", "1e-5", "--log_interval", "8", "--save_interval", "48",
        "--device", "cuda:0",
    ], cwd=root / "trainer", check=True)
    return weight


def evaluate(root, weight, cases):
    import torch
    from eval_toolcall import generate, init_model, parse_tool_calls, setup_seed

    print(f"\n[Evaluating] {weight} on {len(cases)} held-out orders", flush=True)
    args = SimpleNamespace(
        load_from="./model", save_dir="out", weight=weight, hidden_size=768,
        num_hidden_layers=8, use_moe=0, device="cuda", max_new_tokens=128,
        temperature=0.7, top_p=0.9, show_speed=False,
    )
    configure_tools(cases)
    model, tokenizer = init_model(args)
    results = []
    with torch.inference_mode():
        for index, case in enumerate(cases):
            setup_seed(42 + index)
            print(f"[Order] {case[0]}", flush=True)
            results.append(order_eval.run_case(
                case, lambda messages: generate(model, tokenizer, messages, order_eval.TOOLS, args),
                parse_tool_calls,
            ))
    del model, tokenizer
    torch.cuda.empty_cache()
    summary = {
        key: sum(result[key] for result in results)
        for key in ("sequence_ok", "arguments_ok", "amount_ok", "success")
    }
    report = {"weight": weight, "seed": 42, "total": len(cases), "summary": summary, "cases": results}
    path = root / "out" / f"order_grpo_eval_{weight}.json"
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[Summary] {weight}: {summary}, total={len(cases)}", flush=True)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage", choices=("all", "baseline", *MODES), default="all")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if Path.cwd() != root:
        parser.error(f"Run this from the MiniMind root: {root}")
    if not (root / "out" / "order_sft_768.pth").is_file():
        parser.error("Missing out/order_sft_768.pth. Finish the order SFT step first.")
    _, holdout = prepare_data(root)
    if args.stage == "baseline":
        evaluate(root, "order_sft", holdout)
        return

    trainer = root / "trainer" / "train_order_agent.py"
    if trainer.exists() and not trainer.read_text(encoding="utf-8").startswith(GENERATED_HEADER):
        parser.error(f"Refusing to overwrite a custom trainer: {trainer}")
    trainer.write_text(adapt_trainer((root / "trainer" / "train_agent.py").read_text(encoding="utf-8")),
                       encoding="utf-8")

    results = {}
    if args.stage == "all":
        results["order_sft"] = evaluate(root, "order_sft", holdout)
    for mode in MODES if args.stage == "all" else (args.stage,):
        weight = train(root, trainer, mode)
        results[weight] = evaluate(root, weight, holdout)
    print("\n[Comparison] complete successes on the same held-out orders")
    for weight, summary in results.items():
        print(f"{weight}: {summary['success']}/{len(holdout)}")


if __name__ == "__main__":
    main()
